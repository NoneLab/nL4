#!/usr/bin/env bash
# SPDX-License-Identifier: BSD-2-Clause
# The original toolchain offset generation expressed with GCC, nm, awk and sed.
set -euo pipefail
if (( $# != 7 )); then echo "usage: $0 root output profile subarch cxx nm awk" >&2; exit 2; fi
root=$1; out=$2; profile=$3; subarch=$4; cxx=$5; nm=$6; awk=$7
kernel=$root/kernel
cfg=$out/config/config.h
inc=$out/include
mkdir -p "$out/config" "$out/generated" "$inc"
cp "$kernel/config/profiles/$profile/config.h" "$cfg"
cat > "$inc/version.h" <<'EOV'
/* Generated kernel release metadata. */
#define KERNEL_VERSION 0
#define KERNEL_SUBVERSION 4
#define KERNEL_SUBSUBVERSION 0
#define KERNELGENDATE SHUFFLE3(day:12,month:3,year:14)
#define __USER__ "reproducible"
#define __KERNELBUILDNO__ 1
EOV
if [[ $subarch == x64 ]]; then
  cpu=(-m64 -mcmodel=kernel -mno-red-zone)
else
  cpu=(-m32 -mpreferred-stack-boundary=2)
fi
builtin_inc=$($cxx -print-file-name=include)
pp=(-nostdinc "-I$inc" "-I$kernel/src" "-I$kernel/src/generic" "-I$builtin_inc"
  -Ux86 -U"$subarch" -Up4 -Upc99 -Uv4 -Urr
  -D__ARCH__=x86 "-D__SUBARCH__=$subarch" -D__CPU__=p4 -D__PLATFORM__=pc99 -D__API__=v4 -D__SCHED__=rr
  -imacros "$cfg" -imacros "$kernel/src/generic/macros.h" -include "$kernel/src/generic/config.h")
common=(-std=c++11 -ffreestanding -fno-pic -fno-pie -fno-stack-protector -fno-builtin
  -fno-omit-frame-pointer -fno-exceptions -fno-rtti -fno-threadsafe-statics
  -mno-mmx -mno-sse -mno-sse2 -mno-sse3 -O2)
# Offset compiler first sees a dummy version to break bootstrap dependency.
printf '/* bootstrap for offset calculation */\n' > "$inc/tcb_layout.h"
layout="$out/generated/layout.cc"
{
  printf '#include INC_API(tcb.h)\n'
  printf 'tcb_t tcb; utcb_t utcb;\n'
  printf '#define O(sym,val) __asm__ __volatile__("\\n#define " MKSTR(sym) " %%0 " : : "i"(val))\n'
  printf 'void generated_offsets() {\n'
  for spec in 'api/v4/tcb.h TCB tcb_t,' 'glue/v4-x86/ktcb.h TCB_ARCH tcb_t,arch.' \
              'api/v4/sktcb.h TCB_SCHED_STATE tcb_t,sched_state.' 'glue/v4-x86/utcb.h UTCB utcb_t,'; do
    read -r header prefix object <<< "$spec"
    "$awk" '/TCB_END_MARKER/ {inside=0} inside {print} /TCB_START_MARKER/ {inside=1}' "$kernel/src/$header" | \
      "$cxx" -E -x c++ -P -imacros "$cfg" - | \
      "$awk" -v p="$prefix" -v obj="$object" '/;[[:space:]]*$/ {gsub(/\[[^]]*\]/,"",$0); sub(/;.*/,"",$0); if(match($0,/[A-Za-z_][A-Za-z_0-9]*[[:space:]]*$/)) {n=substr($0,RSTART,RLENGTH); gsub(/[[:space:]]/,"",n);print "O(OFS_"p"_"toupper(n)",offsetof("obj n"));"}}'
  done
  printf '}\n'
} > "$layout"
"$cxx" "${pp[@]}" -include "$kernel/src/generic/types.h" "${common[@]}" "${cpu[@]}" \
  -w -DBUILD_TCB_LAYOUT -Dprivate=public -Dprotected=public -S "$layout" -o "$out/generated/layout.s"
{
  printf '#ifndef PISTACHIO_GENERATED_TCB_LAYOUT_H\n#define PISTACHIO_GENERATED_TCB_LAYOUT_H\n'
  sed -n -e '/^#define OFS_/ {s/[$]//g;p;}' "$out/generated/layout.s"
  printf '#endif\n'
} > "$inc/tcb_layout.h.tmp"
test "$(grep -c '^#define OFS_' "$inc/tcb_layout.h.tmp")" -gt 1
mv "$inc/tcb_layout.h.tmp" "$inc/tcb_layout.h"
"$cxx" "${pp[@]}" -include "$kernel/src/generic/types.h" "${common[@]}" "${cpu[@]}" \
 -c "$kernel/src/glue/v4-x86/asmsyms.cc" -o "$out/generated/asmsyms.o"
{
  printf '#ifndef PISTACHIO_GENERATED_ASMSYMS_H\n#define PISTACHIO_GENERATED_ASMSYMS_H\n'
  "$nm" --radix=d -S "$out/generated/asmsyms.o" | "$awk" -f "$root/mk/asm-symbols.awk"
  printf '#endif\n'
} > "$inc/asmsyms.h.tmp"
mv "$inc/asmsyms.h.tmp" "$inc/asmsyms.h"
# Debug profiles require command declarations generated by the historical KDB scanner.
if grep -q '^CONFIG_DEBUG=y' "$kernel/config/profiles/$profile/.config"; then
  mapfile -t kdb_src < "$out/generated/kdb_sources.lst"
  {
    printf '/* Generated KDB command declarations. */\n'
    "$awk" '/^[[:space:]]*DECLARE_CMD[[:space:]]*\(/ {line=$0; sub(/^[[:space:]]*DECLARE_CMD[[:space:]]*\(/,"",line); sub(/,.*/, "", line); gsub(/[[:space:]]/,"",line); print "static cmd_ret_t " line "(cmd_group_t*);"}' "${kdb_src[@]}" "$kernel/src/kdb/cmd.h"
  } > "$inc/kdb_class_helper.h"
  {
    printf '/* Generated KDB member prototypes. */\n'
    "$awk" '/ kdb_t::.*\(/ {line=$0; sub(/kdb_t::/, "", line); sub(/\)[^)]*$/, ");", line); print line}' "${kdb_src[@]}"
  } > "$inc/kdb_autogenerated_protos.h"
fi
# GNU ld script still uses the historical preprocessing macros.
"$cxx" -E -x c -DASSEMBLY "${pp[@]}" -P -C \
 "$kernel/src/glue/v4-x86/$subarch/linker.lds" -o "$out/linker.lds"
touch "$out/generated/headers.stamp"
